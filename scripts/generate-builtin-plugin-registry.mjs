import {
  existsSync,
  readFileSync,
  readdirSync,
  writeFileSync,
} from 'node:fs';
import { join } from 'node:path';
import process from 'node:process';

const pluginsRoot = join('src', 'Plugins');
const outputPath = join('src', 'ZGSTokenBar.Builtins', 'GeneratedBuiltinPluginRegistry.g.cs');

function discover() {
  return readdirSync(pluginsRoot, { withFileTypes: true })
    .filter(entry => entry.isDirectory())
    .map(entry => {
      const directory = join(pluginsRoot, entry.name);
      const manifestPath = join(directory, 'plugin-manifest.v1.json');
      if (!existsSync(manifestPath)) return null;
      const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'));
      const sources = readdirSync(directory)
        .filter(file => file.endsWith('Plugin.cs'))
        .map(file => readFileSync(join(directory, file), 'utf8'));
      const source = sources.find(value => /:\s*BuiltinPluginBase/.test(value));
      if (!source) throw new Error(`No BuiltinPluginBase implementation in ${directory}`);
      const namespaceMatch = source.match(/namespace\s+([A-Za-z0-9_.]+)\s*;/);
      const classMatch = source.match(/public\s+sealed\s+class\s+([A-Za-z0-9_]+)/);
      if (!namespaceMatch || !classMatch) throw new Error(`Cannot parse plugin type in ${directory}`);
      return {
        id: manifest.id,
        order: manifest.order,
        namespace: namespaceMatch[1],
        className: classMatch[1],
      };
    })
    .filter(Boolean)
    .sort((left, right) => left.order - right.order || left.id.localeCompare(right.id));
}

function render(plugins) {
  const usings = plugins
    .map(plugin => `using ${plugin.namespace};`)
    .join('\n');
  const instances = plugins
    .map(plugin => `        new ${plugin.className}(),`)
    .join('\n');
  return `// <auto-generated />
using ZGSTokenBar.PluginSdk;
${usings}

namespace ZGSTokenBar.Builtins;

public static class GeneratedBuiltinPluginRegistry
{
    public static IReadOnlyList<IZgsPlugin> Create() =>
    [
${instances}
    ];
}
`;
}

const expected = render(discover());
if (process.argv.includes('--check')) {
  const actual = readFileSync(outputPath, 'utf8').replaceAll('\r\n', '\n');
  if (actual !== expected) {
    console.error('GeneratedBuiltinPluginRegistry.g.cs is stale.');
    process.exit(1);
  }
  console.log('Built-in plugin registry is current.');
} else {
  writeFileSync(outputPath, expected, 'utf8');
  console.log(`Generated ${outputPath}`);
}
